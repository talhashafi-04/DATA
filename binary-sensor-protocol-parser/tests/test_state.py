def test_hidden_error_priority_ordering(hidden_result_data):
    """Validates that checksum_mismatch takes priority over unknown_sensor_type.

    The hidden fixture at index 5 contains a packet with BOTH a corrupted CRC AND an
    undefined sensor type byte (0xBB). The instruction defines the priority order as:
    truncated_packet > checksum_mismatch > unknown_sensor_type > payload_length_mismatch.
    A correct parser must classify this packet as checksum_mismatch — not
    unknown_sensor_type — because checksum is checked before sensor type in the
    mandated priority order. Any implementation that checks the type before the CRC
    will produce unknown_sensor_type for this packet and fail this test.
    """
    packets = hidden_result_data["packets"]
    pkt = packets[5]
    assert pkt["status"] == "error", f"packets[5] should be an error packet, got status={pkt['status']}"
    assert pkt["error"] == "checksum_mismatch", (
        f"packets[5] has both corrupt CRC and unknown type (0xBB); "
        f"expected error='checksum_mismatch' (CRC is checked first per spec), "
        f"got error='{pkt.get('error')}'"
    )


