def test_output_directory_creation():
    """Validates that the parser creates the output directory if it does not already exist.

    The instruction requires: 'Create the output directory if it does not already exist.'
    This test invokes the parser with an output path whose parent directory does not
    exist prior to the call, then verifies the output file was created. A parser that
    assumes the directory already exists (e.g. by not calling os.makedirs) will raise
    a FileNotFoundError and fail this test.
    """
    out_dir = "/tmp/test_mkdir_newdir"
    out_file = f"{out_dir}/results.json"
    import shutil
    shutil.rmtree(out_dir, ignore_errors=True)
    assert not os.path.exists(out_dir), "Test setup: directory should not exist before parser runs"

    result = subprocess.run(
        ["python3", "/solution/parser.py", "/app/data/sensor_dump.bin", out_file],
        capture_output=True, text=True,
    )
    assert result.returncode == 0, f"Parser failed: {result.stderr}"
    assert os.path.isfile(out_file), f"Output file not created at {out_file}"

    with open(out_file) as f:
        data = json.load(f)
    assert "packets" in data and "summary" in data, "Output JSON missing required keys"

    shutil.rmtree(out_dir, ignore_errors=True)

