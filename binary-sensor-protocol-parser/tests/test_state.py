def test_output_structure(result_data):
    """Validates that results.json has the required top-level keys and correct types.

    The spec mandates a 'packets' list and a 'summary' object. Missing or
    wrong-typed fields indicate a malformed output.
    """
    assert "packets" in result_data, "'packets' key missing from output"
    assert "summary" in result_data, "'summary' key missing from output"
    assert isinstance(result_data["packets"], list)
    summary = result_data["summary"]
    for key in ("total_packets", "valid_packets", "error_packets"):
        assert key in summary, f"summary missing key: {key}"
        assert isinstance(summary[key], int), f"summary['{key}'] must be an integer"
    assert "by_sensor_type" in summary, "'by_sensor_type' missing from summary"
    assert "by_error_type" in summary, "'by_error_type' missing from summary"
    assert isinstance(summary["by_sensor_type"], dict)
    assert isinstance(summary["by_error_type"], dict)


def test_summary_counts(result_data):
    """Validates the summary counts against the known fixture composition.

    The fixture contains 20 total packets: 11 valid and 9 errors (3 checksum
    mismatches, 2 unknown sensor types, 2 payload length mismatches, 2 truncated).
    Two sections of junk bytes are embedded in the stream and must not inflate counts.
    """
    summary = result_data["summary"]
    assert summary["total_packets"] == 20
    assert summary["valid_packets"] == 11
    assert summary["error_packets"] == 9


def test_summary_consistent_with_packets(result_data):
    """Validates that summary values are arithmetically consistent with the packets list.

    Total must equal valid plus error, and each count must match what is actually
    present in the packets array so that the summary cannot be hardcoded separately.
    """
    packets = result_data["packets"]
    summary = result_data["summary"]
    valid_count = sum(1 for p in packets if p.get("status") == "ok")
    error_count = sum(1 for p in packets if p.get("status") == "error")
    assert summary["total_packets"] == len(packets)
    assert summary["valid_packets"] == valid_count
    assert summary["error_packets"] == error_count


