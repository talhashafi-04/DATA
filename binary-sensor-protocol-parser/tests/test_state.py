OUTPUT_FILE = "/app/output/results.json"


@pytest.fixture(scope="session")
def hidden_result_data():
    """Run the agent's parser against a hidden binary fixture and return the parsed JSON.

    The hidden binary is generated by tests/hidden_data/generate.py, which is not
    present in the Docker image (tests/ is not mounted during the agent's solve
    phase). It uses entirely different sensor IDs, timestamps, and values from the
    main fixture, so any agent that hardcodes or derives answers solely from
    /app/data/sensor_dump.bin will fail these tests.

    The hidden fixture contains 7 packets: 2 valid (temperature, humidity) and 5
    errors — two checksum_mismatch (one of which also has an unknown type byte to
    test priority ordering), one unknown_sensor_type, one payload_length_mismatch,
    and one truncated_packet — with a junk byte section between packets to verify
    the parser's scanning logic generalises to unseen input.
    """
    bin_path = "/tmp/hidden_dump.bin"
    json_path = "/tmp/hidden_results.json"

    gen = subprocess.run(
        ["python3", "/tests/hidden_data/generate.py", bin_path],
        capture_output=True, text=True,
    )
    assert gen.returncode == 0, f"Hidden binary generation failed: {gen.stderr}"

    parse = subprocess.run(
        ["python3", "/solution/parser.py", bin_path, json_path],
        capture_output=True, text=True,
    )
    assert parse.returncode == 0, f"Parser failed on hidden binary: {parse.stderr}"

    with open(json_path) as f:
        return json.load(f)



@pytest.fixture(scope="session")
def result_data():
    """Load and return the parsed JSON output produced by the solution."""
    assert os.path.isfile(OUTPUT_FILE), f"Output file not found: {OUTPUT_FILE}"
